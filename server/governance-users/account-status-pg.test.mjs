import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {loadFixtureInput} from '../../../app/server/scripts/wp01/local-config.mjs';
import {withFixtureTransaction} from '../../../app/server/scripts/wp01/fixture-guard.mjs';
import {changeAccountStatus} from './account-status.mjs';
import {inspectAccountBlockers} from './account-blockers.mjs';
import {createHubSession} from '../auth/session.mjs';
const require=createRequire(new URL('../../../app/server/package.json',import.meta.url));
require('ts-node').register({project:new URL('../../../app/server/tsconfig.json',import.meta.url).pathname,transpileOnly:true});
const {AccountsService}=require('./src/accounts/accounts.service.ts'),{JwtService}=require('@nestjs/jwt');
const {env}=loadFixtureInput('../.superpowers/sdd/implementation-plan/wp01-full-baseline-target.json');
const {ids}=JSON.parse(readFileSync('../.tmp/researchhub-knowledge-local/runtime.json','utf8'));
const rollback=Error('P2_STATUS_TEST_ROLLBACK');
test('real legacy stop/restore atomically advances versions and cannot revive old signed Hub credentials',async()=>{
 await assert.rejects(withFixtureTransaction(env,'app',async db=>{
  await db.$executeRaw`SELECT set_config('app.tenant_id',${ids.tenant},true),set_config('app.research_project_id','',true)`;
  const actor=await db.account.findUnique({where:{id:ids.admin}}),principal={tenantId:ids.tenant,accountId:ids.admin,authVersion:actor.authVersion};
  const id='rh-p2-status-'+randomUUID(),target=await db.account.create({data:{id,tenantId:ids.tenant,username:id+'@example.test',displayName:'P2会话回滚对照',passwordHash:'not-a-login-hash'}});
  const jwt=new JwtService({secret:'p2-synthetic-only-test-signature-not-production'});
  const sessions=createHubSession({jwt,scope:{product:'researchhub',deploymentId:'p2-regression',allowedTenantIds:[ids.tenant]},transaction:fn=>fn(db)});
  const before=await sessions.issue({tenantId:ids.tenant,accountId:id,authVersion:0});
  let legacyCalls=0,inspections=0;
  const legacyUpdate=(tx,user,accountId,dto)=>{legacyCalls++;return new AccountsService({withTenantTransaction:(_t,_g,_p,fn)=>fn(tx)}).update(user,accountId,dto);};
  const run=(input,inspectBlockers=async(...args)=>{inspections++;return inspectAccountBlockers(...args);})=>changeAccountStatus({db,principal,input,legacyUpdate,inspectBlockers});
  const stop={targetAccountId:id,status:'disabled',expectedVersion:target.updatedAt.toISOString(),requestKey:randomUUID()};
  const stopped=await run(stop);assert.equal(stopped.authVersion,1);assert.equal(stopped.status,'disabled');
  await assert.rejects(sessions.authenticate(before.token),{status:401});await assert.rejects(sessions.renew(before.token),{status:401});
  const restored=await run({...stop,status:'active',expectedVersion:stopped.version,requestKey:randomUUID()});assert.equal(restored.authVersion,2);
  await assert.rejects(sessions.authenticate(before.token),{status:401});await assert.rejects(sessions.renew(before.token),{status:401});
  const fresh=await sessions.issue({tenantId:ids.tenant,accountId:id,authVersion:2});assert.equal((await sessions.authenticate(fresh.token)).accountId,id);
  assert.deepEqual(await run(stop),stopped);assert.equal(legacyCalls,2);assert.equal(inspections,1);
  const current=await db.account.findUnique({where:{id}});assert.equal(current.authVersion,2);
  await assert.rejects(run({...stop,expectedVersion:current.updatedAt.toISOString(),requestKey:randomUUID()},async()=>['仍有任务执行中']),{code:'HUB_ACCOUNT_DISABLE_BLOCKED'});
  assert.equal((await db.account.findUnique({where:{id}})).authVersion,2);
  await db.$executeRawUnsafe('SAVEPOINT p2_status_failure');
  const broken=new Proxy(db,{get(t,k){return k==='auditLog'?{createMany:async()=>{throw Error('P2_STATUS_AUDIT_FAIL');}}:t[k];}});
  await assert.rejects(changeAccountStatus({db:broken,principal,input:{...stop,expectedVersion:current.updatedAt.toISOString(),requestKey:randomUUID()},legacyUpdate,inspectBlockers:async()=>[]}),/P2_STATUS_AUDIT_FAIL/);
  await db.$executeRawUnsafe('ROLLBACK TO SAVEPOINT p2_status_failure');
  const after=await db.account.findUnique({where:{id}});assert.equal(after.status,'active');assert.equal(after.authVersion,2);
  throw rollback;
 }),e=>e===rollback);
});
