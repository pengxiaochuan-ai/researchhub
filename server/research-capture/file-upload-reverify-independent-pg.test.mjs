import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {createRequire} from 'node:module';
import {readFileSync} from 'node:fs';
import {createVisitFileUploadService} from './file-upload.mjs';
import {createFileLinksService} from './file-links.mjs';
import {createResearchStudiesService} from '../research-studies/commands.mjs';
import {createSyntheticCaptureFixture} from './synthetic-capture-fixture.mjs';
import {setContext} from '../research-studies/repository.mjs';
import {loadFixtureInput} from '../../../app/server/scripts/wp01/local-config.mjs';
import {assertFixtureTarget,withFixtureTransaction,validateFixtureConfig} from '../../../app/server/scripts/wp01/fixture-guard.mjs';

const require=createRequire(new URL('../../../app/server/package.json',import.meta.url));
require('ts-node').register({project:new URL('../../../app/server/tsconfig.json',import.meta.url).pathname,transpileOnly:true});
const {IngestService}=require('./src/ingest/ingest.service.ts');
const {StorageService}=require('./src/storage/storage.service.ts');
const {authorizeIngestInTransaction}=require('./src/ingest/ingest-authorization.ts');
const {readFormalVisitInTransaction}=require('./src/study-operations/formal-response-visits.ts');
const {lockCaptureBinding}=require('./src/study-operations/protocol-migration-lock.ts');
const {lockAuthorizationMutation}=require('./src/common/worker-publication.ts');
const {env}=loadFixtureInput('../.superpowers/sdd/implementation-plan/wp01-full-baseline-target.json');
const code=error=>error.getResponse?.()?.code??error.code;

test('independent real MinIO and aisci_app reverify uses the original actor receipt and current authority without re-ingest',async()=>{
 assert.equal((await assertFixtureTarget(env)).databaseName,'wp01_test_full_baseline');
 const state=JSON.parse(readFileSync('../.tmp/researchhub-knowledge-local/runtime.json','utf8'));
 assert.match(state.key,/^rh-kb-local-[a-f0-9]{8}$/);
 const config=JSON.parse(readFileSync('../.tmp/wp01-pre-release/rehearsal-o7gOnS/runtime.json','utf8')).profiles[0].env;
 assert.equal(config.S3_ENDPOINT,'http://127.0.0.1:19402');
 for(const key of ['S3_ENDPOINT','S3_ACCESS_KEY','S3_SECRET_KEY','S3_REGION'])process.env[key]=config[key];
 process.env.S3_BUCKET=state.key;
 const storage=new StorageService();storage.onModuleInit();
 for(let attempt=0;attempt<50&&!storage.available;attempt++)await new Promise(resolve=>setTimeout(resolve,100));
 assert.equal(storage.available,true);
 const created=new Set(),realPut=storage.put.bind(storage),realRead=storage.getStream.bind(storage);
 let puts=0,reads=0,ingests=0;
 storage.put=async(...args)=>{puts++;const key=await realPut(...args);created.add(key);return key;};
 storage.getStream=async(...args)=>{reads++;return realRead(...args);};
 const prefix=validateFixtureConfig(env).runId+'__reverify_review_'+randomUUID().slice(0,8);
 try{
  await assert.rejects(withFixtureTransaction(env,'direct',async tx=>{
   const fixture=await createSyntheticCaptureFixture(tx,prefix,1),subject=fixture.subjects[0],study=prefix+'_study',roleId=prefix+'_upload_role';
   await tx.permissionRole.create({data:{id:roleId,tenantId:fixture.id.tenant,key:'independent-upload',name:'Synthetic upload role',menuPermissions:['workbench','data'],buttonPermissions:['data.upload']}});
   await tx.studyGroupMembership.create({data:{tenantId:fixture.id.tenant,studyGroupId:fixture.id.group,accountId:fixture.id.account,roleId}});
   await tx.researchProjectMembership.create({data:{...fixture.scope,accountId:fixture.id.account,roleKey:'researcher'}});
   await tx.account.update({where:{id:fixture.id.account},data:{role:'researcher',isTenantAdmin:false}});
   const user={...fixture.user,role:'researcher',isTenantAdmin:false};
   const other=await tx.account.create({data:{id:prefix+'_other',tenantId:fixture.id.tenant,username:'independent-other',displayName:'Synthetic other administrator',passwordHash:'synthetic-only',role:'tenant_admin',isTenantAdmin:true}});
   const otherUser={accountId:other.id,tenantId:fixture.id.tenant,role:other.role,isTenantAdmin:true,authVersion:other.authVersion};
   await tx.$executeRaw`INSERT INTO rh_research.project_intent(id,tenant_id,owner_id,title,status) VALUES (${prefix+'_intent'},${fixture.id.tenant},${user.accountId},'Independent synthetic reverify','study_created')`;
   await tx.$executeRaw`INSERT INTO rh_research.study_binding(id,tenant_id,project_intent_id,execution_project_id,study_group_id) VALUES (${study},${fixture.id.tenant},${prefix+'_intent'},${fixture.id.project},${fixture.id.group})`;
   await setContext(tx,user,fixture.id.group,fixture.id.project);
   await tx.$executeRawUnsafe('SET LOCAL ROLE aisci_app');
   const prisma={withTenantTransaction:async(_tenant,_group,_project,callback)=>callback(tx)};
   const studies=createResearchStudiesService({prisma,scope:{product:'researchhub',allowedTenantIds:[user.tenantId]},lockAuthorization:lockAuthorizationMutation,createResearchProject:async()=>{throw Error('unexpected project creation');}});
   const ingest=new IngestService(prisma,storage,{},{});
   const core={readVisit:readFormalVisitInTransaction,authorizeUpload:(connection,principal,scope)=>authorizeIngestInTransaction(connection,principal,scope.studyGroupId,scope.researchProjectId),lockBinding:lockCaptureBinding};
   const api=createVisitFileUploadService({studies,storage,core:{...core,ingest:async(...args)=>{ingests++;return ingest.ingestPreprocessed(...args);}}});
   const links=createFileLinksService({studies,core:{...core,uploadConfigured:true},cursorSecret:'independent-review-secret'.repeat(2)});
   const bytes=Buffer.from('feature_key,value,unit\nsynthetic.independent,0,unit\n');
   const request={requestKey:'independent-'+randomUUID(),filename:'independent.csv',modality:'eye',contentBase64:bytes.toString('base64')};
   const uploaded=await api.upload(user,study,subject.visitId,request);
   assert.deepEqual(uploaded.storageIntegrity,{status:'verified',recorded:true});
   const file=await tx.modalityFile.findUnique({where:{id:uploaded.fileId}});
   const counts=async()=>({files:await tx.modalityFile.count({where:{tenantId:user.tenantId}}),tasks:await tx.processingTask.count({where:{...fixture.scope}}),features:await tx.feature.count({where:{tenantId:user.tenantId,subjectId:subject.subjectId}}),receipts:(await tx.$queryRaw`SELECT id FROM rh_research.operation WHERE tenant_id=${user.tenantId}`).length,audits:await tx.auditLog.count({where:{tenantId:user.tenantId}})});
   const initial=await counts(),initialReads=reads;
   assert.deepEqual([initial.files,initial.tasks,initial.features,initial.receipts],[1,1,1,1]);
   assert.equal((await links.list(user,study,subject.visitId)).capabilities.canUploadPreprocessed,true);
   await assert.rejects(api.reverify(user,study,subject.visitId,'absent-independent-key'),error=>code(error)==='FILE_RECEIPT_NOT_FOUND');
   await assert.rejects(api.reverify(otherUser,study,subject.visitId,request.requestKey),error=>code(error)==='FILE_RECEIPT_NOT_FOUND');
   assert.deepEqual(await counts(),initial);assert.equal(reads,initialReads);

   await realPut(file.storageKey,Buffer.from('synthetic damaged bytes'),'text/csv');
   const damaged=await api.reverify(user,study,subject.visitId,request.requestKey);
   assert.deepEqual(damaged.storageIntegrity,{status:'mismatch',recorded:false});
   assert.equal((await tx.modalityFile.findUnique({where:{id:file.id}})).meta.storageVerifiedSha256,undefined);
   const invalidation=await tx.auditLog.findFirst({where:{tenantId:user.tenantId,action:'researchhub.file.storage_verification_invalidated',target:file.id},orderBy:{createdAt:'desc'}});
   assert.equal(invalidation.meta.requestKey,request.requestKey);
   await realPut(file.storageKey,bytes,'text/csv');
   const beforeGet=await counts();
   assert.deepEqual((await api.receipt(user,study,subject.visitId,request.requestKey)).storageIntegrity,{status:'verified',recorded:false});
   assert.deepEqual(await counts(),beforeGet);
   assert.equal((await tx.modalityFile.findUnique({where:{id:file.id}})).meta.storageVerifiedSha256,undefined);
   const recovered=await api.reverify(user,study,subject.visitId,request.requestKey);
   assert.deepEqual(recovered.storageIntegrity,{status:'verified',recorded:true});
   assert.equal((await tx.modalityFile.findUnique({where:{id:file.id}})).meta.storageVerifiedSha256,uploaded.sourceSha256);
   const audit=await tx.auditLog.findFirst({where:{tenantId:user.tenantId,action:'researchhub.file.storage_verify',target:file.id},orderBy:{createdAt:'desc'}});
   assert.equal(audit.meta.requestKey,request.requestKey);
   assert.deepEqual(await counts(),{...initial,audits:initial.audits+2});
   assert.equal(ingests,1);assert.equal(puts,1);assert.equal(created.size,1);

   await tx.permissionRole.update({where:{id:roleId},data:{buttonPermissions:[]}});
   const withoutUpload=await links.list(user,study,subject.visitId);
   assert.equal(withoutUpload.items.length,1);assert.equal(withoutUpload.capabilities.canUploadPreprocessed,false);
   const beforeDenied=await counts(),beforeDeniedReads=reads;
   await assert.rejects(api.reverify(user,study,subject.visitId,request.requestKey),error=>code(error)==='IMPORT_AUTHORIZATION_REVOKED');
   assert.deepEqual(await counts(),beforeDenied);assert.equal(reads,beforeDeniedReads);
   await tx.permissionRole.update({where:{id:roleId},data:{buttonPermissions:['data.upload']}});
   await tx.account.update({where:{id:user.accountId},data:{authVersion:{increment:1}}});
   await assert.rejects(api.reverify(user,study,subject.visitId,request.requestKey),error=>code(error)==='AUTH_SESSION_EXPIRED');
   assert.deepEqual(await counts(),beforeDenied);assert.equal(reads,beforeDeniedReads);
   await tx.account.update({where:{id:user.accountId},data:{authVersion:user.authVersion}});
   await tx.studyEnrollment.update({where:{id:subject.enrollmentId},data:{status:'withdrawn'}});
   await assert.rejects(api.reverify(user,study,subject.visitId,request.requestKey),error=>code(error)==='PARTICIPATION_CAPTURE_BLOCKED');
   assert.deepEqual(await counts(),beforeDenied);assert.equal(reads,beforeDeniedReads);
   assert.equal(ingests,1);assert.equal(puts,1);
   throw Error('INDEPENDENT_REVERIFY_ALL_ROLLBACK');
  }),/INDEPENDENT_REVERIFY_ALL_ROLLBACK/);
 }finally{
  for(const key of created)await storage.remove(key);
 }
});
